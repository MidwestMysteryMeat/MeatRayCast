--[[
    meatray.sim.world — the tile grid and its doors.

    A world is a plain 2D array of tile codes plus per-tile door state. The
    engine works with any grid you hand it, whether generated by
    meatray.sim.worldgen or authored by hand, so nothing here depends on the
    generator.

    Tile codes:
        0            empty / walkable
        1..9         solid wall, the number selects a wall texture
        DOOR (10)    door, blocking while closed, walkable while open
        STAIRS_UP    (11) and STAIRS_DOWN (12): walkable markers
        RUBBLE (13)  what a destroyed wall leaves behind: walkable, and not
                     drawn as a wall -- the renderer casts straight through it,
                     so a destroyed wall reads as a hole. Debris on the floor is
                     a billboard the game spawns, not a tile.

    Wall HEIGHT is a side table, not a tile code: a solid tile is full height
    (1.0) unless setWallHeight says otherwise. Short walls (0 < h < 1) still
    block movement and still stop hitscan, but the renderer lets the ray
    continue past them so geometry behind shows over the top. That is the cheap
    half of variable height — one floor plane, no stacked levels. Stacked floors
    would collapse the per-column z-buffer; see docs/RESEARCH.md.

    Two things about a world change while it is running: doors open, and walls
    come down. They are tracked the same way -- a side table keyed by tile, a
    snapshot that lists only what differs from the map as authored, and an apply
    that takes such a list. Doing destruction as a second copy of the door
    mechanism rather than as a new mechanism is deliberate: the save system and
    the network layer already know how to carry one of these, so they carry two
    without learning anything.

    HEADLESS: this module must not touch love.graphics or any love drawing API.
]]

local World = {}

World.EMPTY       = 0
World.DOOR        = 10
World.STAIRS_UP   = 11
World.STAIRS_DOWN = 12
World.RUBBLE      = 13

local WorldMT = {}
WorldMT.__index = WorldMT

-- Absolute z stride between stacked storeys. Storey 1 is [0, H), storey 2 is
-- [H, 2H), etc. Within a storey, floor/ceiling heights stay relative 0..1.
World.STOREY_HEIGHT = 1.0

local function makeLayer(grid, opts)
    opts = opts or {}
    return {
        grid = grid,
        doors = opts.doors or {},
        integrity = opts.integrity or {},
        broken = opts.broken or {},
        wallHeights = opts.wallHeights or {},
        wallSlabs = opts.wallSlabs or {},
        floorHeights = opts.floorHeights or {},
        ceilingHeights = opts.ceilingHeights or {},
        segments = opts.segments,
        spawn = opts.spawn,
    }
end

-- Wraps a tile grid. `grid` is indexed grid[y][x] with 1-based integer tiles,
-- matching the convention worldgen emits.
--
-- Multi-storey: world.layers[1..N] each hold a full plan. Top-level grid/doors/
-- floorHeights/… are the same tables as layers[1] so one-layer maps and all
-- existing call sites stay valid. Pass storey as the last arg to tile/solid/
-- door/floor helpers when not on storey 1. See docs/STOREYS.md.
function World.new(grid, opts)
    opts = opts or {}
    assert(type(grid) == 'table' and type(grid[1]) == 'table', 'world needs a grid[y][x]')

    local layer1 = makeLayer(grid, {
        wallHeights = opts.wallHeights,
        wallSlabs = opts.wallSlabs,
        floorHeights = opts.floorHeights,
        ceilingHeights = opts.ceilingHeights,
        segments = opts.segments,
        spawn = opts.spawn,
        doors = opts.doors,
        integrity = opts.integrity,
        broken = opts.broken,
    })

    local layers = { layer1 }
    if opts.extraLayers then
        for i = 1, #opts.extraLayers do
            local L = opts.extraLayers[i]
            layers[#layers + 1] = makeLayer(L.grid, L)
        end
    end

    return setmetatable({
        -- Layer 1 aliases (same table references as layers[1]).
        grid = layer1.grid,
        height = #layer1.grid,
        width = #layer1.grid[1],
        doors = layer1.doors,
        integrity = layer1.integrity,
        broken = layer1.broken,
        wallHeights = layer1.wallHeights,
        wallSlabs = layer1.wallSlabs,
        floorHeights = layer1.floorHeights,
        ceilingHeights = layer1.ceilingHeights,
        segments = layer1.segments,

        layers = layers,

        theme = opts.theme,
        spawn = opts.spawn or layer1.spawn,
        -- Multi-map storey links (separate from in-world layers).
        links = opts.links,

        revision = 0,
    }, WorldMT)
end

function WorldMT:storeyCount()
    return #(self.layers or { 1 })
end

function WorldMT:layer(storey)
    local n = self:storeyCount()
    local s = tonumber(storey) or 1
    if s < 1 then s = 1 end
    if s > n then s = n end
    return self.layers[s]
end

function WorldMT:storeyBase(storey)
    local s = tonumber(storey) or 1
    if s < 1 then s = 1 end
    return (s - 1) * (World.STOREY_HEIGHT or 1)
end

-- Append a storey (same width/height grid). Returns the new storey index.
function WorldMT:addStorey(grid, opts)
    opts = opts or {}
    assert(type(grid) == 'table' and type(grid[1]) == 'table', 'addStorey needs a grid')
    assert(#grid == self.height, 'storey grid height must match world')
    assert(#grid[1] == self.width, 'storey grid width must match world')
    local L = makeLayer(grid, opts)
    self.layers[#self.layers + 1] = L
    self.revision = (self.revision or 0) + 1
    return #self.layers
end

function WorldMT:inBounds(tx, ty)
    return tx >= 1 and ty >= 1 and tx <= self.width and ty <= self.height
end

-- Out of bounds reads as solid so rays and movement stop at the edge rather
-- than indexing nil. Optional storey (default 1).
function WorldMT:tileAt(tx, ty, storey)
    if not self:inBounds(tx, ty) then return 1 end
    local L = self:layer(storey or 1)
    return L.grid[ty][tx] or World.EMPTY
end

-- Within-layer table key (each layer has its own doors/broken/integrity).
local function doorKey(tx, ty)
    return tx .. ',' .. ty
end

-- Wire / snapshot key. Storey 1 stays "tx,ty" so single-layer maps and old
-- saves keep their format. Storey ≥2 is "s,tx,ty".
local function stateKey(tx, ty, storey)
    storey = storey or 1
    if storey <= 1 then return tx .. ',' .. ty end
    return storey .. ',' .. tx .. ',' .. ty
end

-- Inverse of stateKey. Returns tx, ty, storey or nil.
local function parseStateKey(key)
    key = tostring(key or '')
    local s, x, y = key:match('^(%d+),(%-?%d+),(%-?%d+)$')
    if s then return tonumber(x), tonumber(y), tonumber(s) end
    local x2, y2 = key:match('^(%-?%d+),(%-?%d+)$')
    if x2 then return tonumber(x2), tonumber(y2), 1 end
    return nil
end

World.stateKey = stateKey
World.parseStateKey = parseStateKey

function WorldMT:doorAt(tx, ty, storey)
    return self:layer(storey or 1).doors[doorKey(tx, ty)]
end

-- Registers a door on a tile. Doors are tracked separately from the grid so a
-- door's open state can change without rewriting the map.
function WorldMT:addDoor(tx, ty, open, storey)
    local L = self:layer(storey or 1)
    L.grid[ty][tx] = World.DOOR
    L.doors[doorKey(tx, ty)] = { open = open or false, openness = open and 1 or 0 }
    return self
end

-- Notifies watchers that solidity at (tx, ty) may have changed. Gas fields and
-- anything else that caches "what can flow through here" subscribe once; the
-- world emits, so a caller that opens a door or knocks a wall down cannot forget
-- to wake them. `onShapeChange` is still honoured for one-off hooks.
-- Optional 4th arg is storey (default 1); older watchers that only take three
-- args keep working because Lua ignores extra parameters.
function WorldMT:_emitShapeChange(tx, ty, kind, storey)
    storey = storey or 1
    local list = self._shapeWatchers
    if list then
        for i = 1, #list do
            list[i](self, tx, ty, kind, storey)
        end
    end
    if self.onShapeChange then
        self.onShapeChange(self, tx, ty, kind, storey)
    end
end

-- Subscribe to door open/close, destruction and repair. Returns an unsubscribe
-- function. Order of delivery is registration order; a watcher that raises is
-- not caught — the shape change already happened, and hiding the error would
-- only make the gas (or whatever) silently wrong.
function WorldMT:watchShape(fn)
    if type(fn) ~= 'function' then
        error('world:watchShape needs a function', 2)
    end
    local list = self._shapeWatchers
    if not list then
        list = {}
        self._shapeWatchers = list
    end
    list[#list + 1] = fn
    return function()
        for i = #list, 1, -1 do
            if list[i] == fn then
                table.remove(list, i)
                return
            end
        end
    end
end

function WorldMT:setDoorOpen(tx, ty, open, storey)
    storey = storey or 1
    local door = self:doorAt(tx, ty, storey)
    if not door then return false end
    local want = open and true or false
    if door.open == want then return true end
    door.open = want
    self:_emitShapeChange(tx, ty, 'door', storey)
    return true
end

function WorldMT:toggleDoor(tx, ty, storey)
    storey = storey or 1
    local door = self:doorAt(tx, ty, storey)
    if not door then return false end
    door.open = not door.open
    self:_emitShapeChange(tx, ty, 'door', storey)
    return true
end

-- Blocks movement and rays. A door blocks only while shut.
function WorldMT:isSolid(tx, ty, storey)
    local tile = self:tileAt(tx, ty, storey)
    if tile == World.EMPTY then return false end
    if tile == World.STAIRS_UP or tile == World.STAIRS_DOWN then return false end
    if tile == World.RUBBLE then return false end
    if tile == World.DOOR then
        local door = self:doorAt(tx, ty, storey)
        return not (door and door.open)
    end
    return true
end

-- True for tiles a walker may occupy, which is the same question as isSolid for
-- now but kept separate: games add hazards and one-way tiles here.
function WorldMT:isWalkable(tx, ty, storey)
    return not self:isSolid(tx, ty, storey)
end

-- Advances door animation on every storey.
function WorldMT:update(dt, speed)
    speed = speed or 4
    for si = 1, self:storeyCount() do
        local doors = self:layer(si).doors
        for _, door in pairs(doors) do
            local target = door.open and 1 or 0
            if door.openness ~= target then
                local step = speed * dt
                if door.openness < target then
                    door.openness = math.min(target, door.openness + step)
                else
                    door.openness = math.max(target, door.openness - step)
                end
            end
        end
    end
end

---------------------------------------------------------------------------
-- Thin walls
--
-- A tile grid only makes walls at right angles on a lattice, which is why every
-- raycaster built on one looks like it was built on one. A segment is a line
-- between two arbitrary points, and it is opaque and full height -- see
-- meatray/sim/segments.lua for why those two limits are where the affordable
-- version stops.
---------------------------------------------------------------------------

function WorldMT:addSegment(x1, y1, x2, y2, tex, opts)
    if not self.segments then
        self.segments = require('meatray.sim.segments').new()
    end
    return self.segments:add(x1, y1, x2, y2, tex, opts)
end

function WorldMT:segmentCount()
    return self.segments and self.segments.count or 0
end

function WorldMT:clearSegments()
    if self.segments then self.segments:clear() end
    return self
end

---------------------------------------------------------------------------
-- Wall height and slabs (variable geometry on one floor plane)
--
-- A solid tile is a full wall (one slab base=0 height=1) until told otherwise.
-- Two ways to say otherwise:
--
--   setWallHeight(tx, ty, h)     one slab on the floor, height h in (0, 1]
--   addWallSlab(tx, ty, base, h) a slab at base z, height h; several per tile
--
-- Stacked / floating walls are just multiple slabs. The renderer records every
-- slab the ray hits and continues past any tile that does not cover the full
-- [0, 1] range, so a gap at eye height lets you see what is behind. Movement
-- and isSolid are unchanged — you still cannot walk through a half-height
-- pillar. Setting geometry on a non-solid tile is refused.
--
-- This is still one floor plane (camera at EYE_HEIGHT, no pitch). Multi-level
-- *floors* you can walk on are a different feature.
---------------------------------------------------------------------------

-- Camera eye height in wall units, matching the wall loop's assumption that a
-- full wall is centred on the horizon (eye at mid-height).
World.EYE_HEIGHT = 0.5

local DEFAULT_SLABS = { { base = 0, height = 1 } }

-- True when a floor-based wall of this height fully occludes the camera eye.
function World.occludesEye(height)
    height = height or 1
    return height >= World.EYE_HEIGHT
end

-- True when a slab [base, base+height) covers the eye height. `eye` defaults
-- to EYE_HEIGHT; pass the camera's absolute eyeZ when standing on a raised
-- floor so occlusion matches what the player can actually see over.
function World.slabOccludesEye(base, height, eye)
    base = base or 0
    height = height or 1
    local top = base + height
    eye = eye or World.EYE_HEIGHT
    return base <= eye and top > eye - 1e-9
end

-- True when the union of slabs covers [0, 1] with no gaps — a ray-stopping
-- face. Insertion-merge on a sorted list; n is small (one or two slabs).
function World.slabsBlockRay(slabs)
    if not slabs or #slabs == 0 then return true end
    local spans = {}
    for i = 1, #slabs do
        local s = slabs[i]
        local b, h = s.base or 0, s.height or 1
        if h > 0 then spans[#spans + 1] = { b, b + h } end
    end
    if #spans == 0 then return false end
    table.sort(spans, function(a, b) return a[1] < b[1] end)

    local coverLo, coverHi = spans[1][1], spans[1][2]
    for i = 2, #spans do
        if spans[i][1] <= coverHi + 1e-9 then
            if spans[i][2] > coverHi then coverHi = spans[i][2] end
        else
            break
        end
    end
    return coverLo <= 1e-9 and coverHi >= 1 - 1e-9
end

-- Returns the slab list for a tile. Never nil; default is one full wall.
-- The returned table must not be mutated by the caller — it may be shared.
-- Relative bases within the storey (0..1); add storeyBase for absolute z.
function WorldMT:wallSlabsAt(tx, ty, storey)
    if not self:inBounds(tx, ty) then return DEFAULT_SLABS end
    local L = self:layer(storey or 1)
    local key = doorKey(tx, ty)
    local slabs = L.wallSlabs[key]
    if slabs and #slabs > 0 then return slabs end
    local h = L.wallHeights[key]
    if h ~= nil then
        return { { base = 0, height = h } }
    end
    return DEFAULT_SLABS
end

-- Convenience: height of a single floor-based slab, or 1 for full/default, or
-- the top of the highest slab when geometry is stacked.
function WorldMT:wallHeightAt(tx, ty, storey)
    if not self:inBounds(tx, ty) then return 1 end
    local L = self:layer(storey or 1)
    local key = doorKey(tx, ty)
    if L.wallHeights[key] ~= nil then return L.wallHeights[key] end
    local slabs = L.wallSlabs[key]
    if not slabs or #slabs == 0 then return 1 end
    if #slabs == 1 and (slabs[1].base or 0) <= 1e-9 then
        return slabs[1].height or 1
    end
    local top = 0
    for i = 1, #slabs do
        local s = slabs[i]
        local t = (s.base or 0) + (s.height or 0)
        if t > top then top = t end
    end
    return top
end

-- Sets a single floor-based short wall. Pass nil or 1 to clear to full height.
function WorldMT:setWallHeight(tx, ty, height, storey)
    if not self:inBounds(tx, ty) then return false end
    if not self:isSolid(tx, ty, storey) then return false end

    local L = self:layer(storey or 1)
    local key = doorKey(tx, ty)
    L.wallSlabs[key] = nil

    if height == nil or height >= 1 then
        L.wallHeights[key] = nil
        return true
    end

    if type(height) ~= 'number' or height ~= height then return false end
    if height <= 0 then return false end

    L.wallHeights[key] = height
    return true
end

-- Adds a slab at base z with the given height. Both relative within the storey.
function WorldMT:addWallSlab(tx, ty, base, height, storey)
    if not self:inBounds(tx, ty) then return false end
    if not self:isSolid(tx, ty, storey) then return false end
    if type(base) ~= 'number' or base ~= base or base < 0 then return false end
    if type(height) ~= 'number' or height ~= height or height <= 0 then return false end

    local L = self:layer(storey or 1)
    local key = doorKey(tx, ty)
    L.wallHeights[key] = nil

    local list = L.wallSlabs[key]
    if not list then
        list = {}
        L.wallSlabs[key] = list
    end
    list[#list + 1] = { base = base, height = height }
    table.sort(list, function(a, b) return (a.base or 0) < (b.base or 0) end)
    return true
end

-- Replaces all slabs on a tile. Pass nil or {} to clear to full height.
function WorldMT:setWallSlabs(tx, ty, slabs, storey)
    if not self:inBounds(tx, ty) then return false end
    if not self:isSolid(tx, ty, storey) then return false end

    local L = self:layer(storey or 1)
    local key = doorKey(tx, ty)
    L.wallHeights[key] = nil

    if slabs == nil or (type(slabs) == 'table' and #slabs == 0) then
        L.wallSlabs[key] = nil
        return true
    end
    if type(slabs) ~= 'table' then return false end

    local list = {}
    for i = 1, #slabs do
        local s = slabs[i]
        local b, h = s.base or 0, s.height or 0
        if type(b) == 'number' and b == b and b >= 0
           and type(h) == 'number' and h == h and h > 0 then
            list[#list + 1] = { base = b, height = h }
        end
    end
    if #list == 0 then
        L.wallSlabs[key] = nil
        return true
    end
    if #list == 1 and list[1].base <= 1e-9 and list[1].height >= 1 - 1e-9 then
        L.wallSlabs[key] = nil
        return true
    end
    if #list == 1 and list[1].base <= 1e-9 and list[1].height < 1 then
        L.wallHeights[key] = list[1].height
        L.wallSlabs[key] = nil
        return true
    end
    table.sort(list, function(a, b) return a.base < b.base end)
    L.wallSlabs[key] = list
    return true
end

---------------------------------------------------------------------------
-- Floor height (walkable elevation) — relative within a storey (0..1 band).
-- Absolute feet z = storeyBase(storey) + floorHeightAt(...).
---------------------------------------------------------------------------

function WorldMT:floorHeightAt(tx, ty, storey)
    if not self:inBounds(tx, ty) then return 0 end
    local L = self:layer(storey or 1)
    return L.floorHeights[doorKey(tx, ty)] or 0
end

-- Absolute walk surface under a point (storey base + relative).
function WorldMT:absoluteFloorAt(tx, ty, storey)
    storey = storey or 1
    return self:storeyBase(storey) + self:floorHeightAt(tx, ty, storey)
end

function WorldMT:floorHeightAtPoint(x, y, storey)
    local tx, ty = math.floor(x) + 1, math.floor(y) + 1
    return self:floorHeightAt(tx, ty, storey)
end

function WorldMT:absoluteFloorAtPoint(x, y, storey)
    local tx, ty = math.floor(x) + 1, math.floor(y) + 1
    return self:absoluteFloorAt(tx, ty, storey)
end

function WorldMT:setFloorHeight(tx, ty, height, opts)
    if not self:inBounds(tx, ty) then return false end
    local storey = opts and opts.storey or 1
    local L = self:layer(storey)
    local key = doorKey(tx, ty)
    if height == nil or height == 0 then
        L.floorHeights[key] = nil
    else
        if type(height) ~= 'number' or height ~= height then return false end
        if height < 0 then return false end
        L.floorHeights[key] = height
    end
    self.revision = (self.revision or 0) + 1
    if not (opts and opts.defer) then
        self:rebuildFloorRisers(storey)
    end
    return true
end

-- Relative floor planes on a storey (for multi-plane cast within that storey).
function WorldMT:floorHeightPlanes(storey)
    local L = self:layer(storey or 1)
    local seen, list = { [0] = true }, { 0 }
    for _, z in pairs(L.floorHeights) do
        if type(z) == 'number' and z > 0 and not seen[z] then
            seen[z] = true
            list[#list + 1] = z
        end
    end
    table.sort(list)
    return list
end

function WorldMT:ceilingHeightAt(tx, ty, storey)
    if not self:inBounds(tx, ty) then return 1 end
    local L = self:layer(storey or 1)
    return L.ceilingHeights[doorKey(tx, ty)] or 1
end

function WorldMT:absoluteCeilingAt(tx, ty, storey)
    storey = storey or 1
    return self:storeyBase(storey) + self:ceilingHeightAt(tx, ty, storey)
end

function WorldMT:ceilingHeightAtPoint(x, y, storey)
    local tx, ty = math.floor(x) + 1, math.floor(y) + 1
    return self:ceilingHeightAt(tx, ty, storey)
end

function WorldMT:setCeilingHeight(tx, ty, height, opts)
    if not self:inBounds(tx, ty) then return false end
    local storey = opts and opts.storey or 1
    local L = self:layer(storey)
    local key = doorKey(tx, ty)
    if height == nil or height == 1 then
        L.ceilingHeights[key] = nil
    else
        if type(height) ~= 'number' or height ~= height then return false end
        if height < 0 then return false end
        L.ceilingHeights[key] = height
    end
    self.revision = (self.revision or 0) + 1
    return true
end

function WorldMT:ceilingHeightPlanes(storey)
    local L = self:layer(storey or 1)
    local seen, list = { [1] = true }, { 1 }
    for _, z in pairs(L.ceilingHeights) do
        if type(z) == 'number' and z ~= 1 and not seen[z] then
            seen[z] = true
            list[#list + 1] = z
        end
    end
    table.sort(list)
    return list
end

-- Rebuild risers for a storey (default 1). Segments live on the world for v1
-- (shared); only storey-1 risers are used by the active-storey render path.
function WorldMT:rebuildFloorRisers(storey)
    storey = storey or 1
    if self.segments then
        self.segments:clearAuto()
    end

    local L = self:layer(storey)
    local any = false
    for _ in pairs(L.floorHeights) do any = true; break end
    if not any then return self end

    local DX = { 1, -1, 0, 0 }
    local DY = { 0, 0, 1, -1 }
    local function edge(tx, ty, dx, dy)
        if dx == 1 then
            return tx, ty - 1, tx, ty
        elseif dx == -1 then
            return tx - 1, ty - 1, tx - 1, ty
        elseif dy == 1 then
            return tx - 1, ty, tx, ty
        else
            return tx - 1, ty - 1, tx, ty - 1
        end
    end

    for key, hi in pairs(L.floorHeights) do
        local sx, sy = key:match('^(%-?%d+),(%-?%d+)$')
        local tx, ty = tonumber(sx), tonumber(sy)
        if tx and ty and hi and hi > 0 and not self:isSolid(tx, ty, storey) then
            for k = 1, 4 do
                local nx, ny = tx + DX[k], ty + DY[k]
                if self:inBounds(nx, ny) and not self:isSolid(nx, ny, storey) then
                    local lo = self:floorHeightAt(nx, ny, storey)
                    if hi > lo + 1e-9 then
                        local x1, y1, x2, y2 = edge(tx, ty, DX[k], DY[k])
                        self:addSegment(x1, y1, x2, y2, {
                            tex = 1,
                            base = lo,
                            height = hi - lo,
                            auto = true,
                        })
                    end
                end
            end
        end
    end
    return self
end

---------------------------------------------------------------------------
-- Destruction
--
-- A wall is destructible only once something says so. That is the opposite of
-- the obvious design, where every wall has hit points and most of them are set
-- to infinity, and it is chosen because the common case in a level is a wall
-- that must never come down. Making indestructibility the default means a map
-- cannot accidentally become perforated by a stray explosion, and it keeps the
-- side table proportional to the number of breakable walls rather than to the
-- size of the map.
---------------------------------------------------------------------------

-- Marks a tile as breakable with `hp` hit points. Returns false for a tile that
-- is not currently solid, since there is nothing there to break.
-- Optional storey (default 1) selects the layer.
function WorldMT:setDestructible(tx, ty, hp, storey)
    if not self:inBounds(tx, ty) then return false end
    if not self:isSolid(tx, ty, storey) then return false end
    local L = self:layer(storey or 1)
    L.integrity[doorKey(tx, ty)] = hp or 100
    return true
end

function WorldMT:integrityAt(tx, ty, storey)
    return self:layer(storey or 1).integrity[doorKey(tx, ty)]
end

function WorldMT:isDestructible(tx, ty, storey)
    return self:layer(storey or 1).integrity[doorKey(tx, ty)] ~= nil
end

-- Applies damage. Returns destroyed(bool), hpRemaining.
--
-- Damage to a tile that was never marked destructible does nothing and reports
-- nothing -- an explosion is allowed to splash across a whole room and ask every
-- tile in it, and the ones that cannot break are not an error.
function WorldMT:damageTile(tx, ty, amount, storey)
    storey = storey or 1
    local L = self:layer(storey)
    local key = doorKey(tx, ty)
    local hp = L.integrity[key]
    if hp == nil then return false, nil end

    hp = hp - (amount or 0)

    if hp > 0 then
        L.integrity[key] = hp
        return false, hp
    end

    self:destroyTile(tx, ty, storey)
    return true, 0
end

-- Brings a tile down regardless of hit points. Remembers what it was, both so a
-- save can describe the change as a difference from the authored map and so a
-- game can repair it. Optional storey (default 1).
function WorldMT:destroyTile(tx, ty, storey)
    storey = storey or 1
    if not self:inBounds(tx, ty) then return false end

    local L = self:layer(storey)
    local key = doorKey(tx, ty)
    local was = L.grid[ty][tx]
    if was == World.RUBBLE then return false end

    L.broken[key] = was
    L.integrity[key] = nil
    L.wallHeights[key] = nil
    L.wallSlabs[key] = nil
    L.grid[ty][tx] = World.RUBBLE
    self.revision = self.revision + 1

    -- Told, not polled -- and unlike the revision counter this one is a single
    -- game-owned hook rather than a cache. Debris is a thing that happens once,
    -- at a known place, with the tile code that was there; reconstructing that
    -- by diffing the grid against last frame would be worse in every way.
    --
    -- It fires on the client too, during a world delta apply, which is what you
    -- want: debris is cosmetic, so every machine spawning its own from the same
    -- event costs no bandwidth and needs no replication.
    -- Fifth arg is storey (1 for single-layer maps); older hooks ignore it.
    if self.onDestroy then self.onDestroy(self, tx, ty, was, storey) end

    -- A destroyed door stops being a door. Leaving the entry behind would give
    -- the animation loop something to keep stepping and would let isSolid
    -- consult a door on a tile that is now a hole.
    L.doors[key] = nil

    -- Gas (and anything else that sleeps on "solidity did not change") has to
    -- learn the hole opened. Same emission as a door toggle.
    self:_emitShapeChange(tx, ty, 'destroy', storey)

    return true
end

-- Puts a destroyed tile back. The inverse exists because destruction is state
-- like any other: a level that reloads, a round that restarts, or an undo in
-- the editor all need it, and reconstructing the original grid from the map
-- file is a much bigger hammer.
function WorldMT:repairTile(tx, ty, hp, storey)
    storey = storey or 1
    local L = self:layer(storey)
    local key = doorKey(tx, ty)
    local was = L.broken[key]
    if was == nil then return false end

    L.grid[ty][tx] = was
    L.broken[key] = nil
    self.revision = self.revision + 1

    if hp then L.integrity[key] = hp end
    self:_emitShapeChange(tx, ty, 'repair', storey)
    return true
end

-- What changed relative to the map as authored. Mirrors :snapshot() for doors,
-- deliberately: same key format, same "only the differences" rule, so the net
-- and save layers carry it with the code they already have.
-- Multi-storey: keys for storey ≥2 are "s,tx,ty"; storey 1 stays "tx,ty".
function WorldMT:tileSnapshot()
    local out = {}
    for si = 1, self:storeyCount() do
        local broken = self:layer(si).broken
        for key in pairs(broken) do
            local tx, ty = key:match('^(%-?%d+),(%-?%d+)$')
            if tx then
                out[stateKey(tonumber(tx), tonumber(ty), si)] = 1
            end
        end
    end
    return out
end

function WorldMT:applyTileSnapshot(snap)
    if not snap then return self end

    for key, gone in pairs(snap) do
        local tx, ty, storey = parseStateKey(key)
        if tx and ty and self:inBounds(tx, ty) then
            local L = self:layer(storey)
            local layerKey = doorKey(tx, ty)
            if gone == 1 then
                if L.broken[layerKey] == nil then
                    self:destroyTile(tx, ty, storey)
                end
            else
                self:repairTile(tx, ty, nil, storey)
            end
        end
    end

    return self
end

-- Door state across every layer. Storey 1 keys stay "tx,ty"; upper storeys use
-- "s,tx,ty". Same tables the network and save system already carry.
function WorldMT:snapshot()
    local out = {}
    for si = 1, self:storeyCount() do
        local doors = self:layer(si).doors
        for key, door in pairs(doors) do
            local tx, ty = key:match('^(%-?%d+),(%-?%d+)$')
            if tx then
                out[stateKey(tonumber(tx), tonumber(ty), si)] = door.open and 1 or 0
            end
        end
    end
    return out
end

function WorldMT:applySnapshot(snap)
    if not snap then return self end
    for key, open in pairs(snap) do
        local tx, ty, storey = parseStateKey(key)
        if tx then
            local door = self:doorAt(tx, ty, storey)
            if door then door.open = (open == 1) end
        end
    end
    return self
end

return World
